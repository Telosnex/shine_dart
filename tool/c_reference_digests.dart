// Writes test/c_reference_digests.dart: the SHA-256 of the C encoder's
// output for test/support/signal.dart at every supported sample rate,
// channel count and bitrate.
//
// Build shineenc from https://github.com/toots/shine (commit in the output):
//   cc -O2 -o shineenc -Isrc/lib src/lib/*.c src/bin/*.c -lm
// Then: dart run tool/c_reference_digests.dart <path to shineenc> <commit>
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:shine_dart/shine.dart';

import '../test/support/signal.dart';
import '../test/support/configs.dart';

Future<void> main(List<String> args) async {
  if (args.length != 2) {
    stderr.writeln(
        'usage: dart run tool/c_reference_digests.dart <shineenc> <commit>');
    exit(64);
  }
  final shineenc = args[0];
  final temp = await Directory.systemTemp.createTemp('shine-reference-');
  final lines = <String>[];
  try {
    for (final rate in kSampleRates) {
      for (final channels in [1, 2]) {
        final wav = File('${temp.path}/in_${rate}_$channels.wav')
          ..writeAsBytesSync(testSignalWav(rate, channels, framesFor(rate)));
        for (final bitrate in kBitrates) {
          if (shineCheckConfig(rate, bitrate) < 0) continue;
          final mp3 = '${temp.path}/out.mp3';
          final run = await Process.run(
              shineenc, ['-q', '-b', '$bitrate', wav.path, mp3]);
          if (run.exitCode != 0) {
            throw StateError(
                'shineenc $rate $channels $bitrate: ${run.stderr}');
          }
          final digest = sha256.convert(File(mp3).readAsBytesSync());
          lines.add("  '${configKey(rate, channels, bitrate)}': '$digest',");
        }
      }
    }
  } finally {
    temp.deleteSync(recursive: true);
  }
  File('test/c_reference_digests.dart').writeAsStringSync('''
// GENERATED by tool/c_reference_digests.dart. Do not edit.
// SHA-256 of the C shineenc output (toots/shine ${args[1]}) for
// test/support/signal.dart.
const kCReferenceDigests = <String, String>{
${lines.join('\n')}
};
''');
  stdout.writeln('${lines.length} configurations.');
}
